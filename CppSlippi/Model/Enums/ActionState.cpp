Action ActionMapper::toAction(ActionState actionState) const {
	uint16_t actionStateValue = actionState;
	if (actionStateValue < ActionState::kNumCommonActionStates) {
		return commonMapper_.toAction[actionState];
	} else if (actionStateValue < ActionState::kNumActionStates) {
		return characterMapper_.toAction[actionStateValue - ActionState::kNumCommonActionStates];
	} else {
		return Action::UNKNOWN;
	}
}

ActionState ActionMapper::toActionState(Action action) const {
	int16_t actionValue = action;
	ActionState actionState;
	if (actionValue <= Action::UNKNOWN || actionValue >= Action::kNumActions) {
		throw NoKnownActionStateException(
			std::format("Action with value {} does not exist.", static_cast<uint8_t>(action)));
	} else if (actionValue < Action::kNumCommonActions) {
		actionState = commonMapper_.toActionState[action];
	} else {
		actionState = characterMapper_.toActionState[actionValue - Action::kNumCommonActions];
	}

	if (actionState == static_cast<ActionState>(-1)) {
		throw NoKnownActionStateException(
			std::format("Action {} does not exist for {}.", action.toString(), character_.toString()));
	}
	return actionState;
}

