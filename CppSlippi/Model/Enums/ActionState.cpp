class SubsetMapper {
private:
	static constexpr uint16_t kNumCharacterActionStates = ActionState::kNumActionStates - ActionState::kNumCommonActionStates;
	static constexpr uint16_t kNumMapperActionStates = std::max(ActionState::kNumCommonActionStates, kNumCharacterActionStates);

	static constexpr std::array<Action, kNumMapperActionStates> buildToAction(
			std::initializer_list<std::pair<uint16_t, Action>> actions) {
		std::array<Action, kNumMapperActionStates> map;
		map.fill(Action::UNKNOWN);
		for (auto [i, action] : actions) {
			if (i >= ActionState::kNumCommonActionStates) {
				map[i - ActionState::kNumCommonActionStates] = action;
			} else {
				map[i] = action;
			}
		}
		return map;
	}

	static constexpr std::array<ActionState, Action::kNumActions> buildToActionState(
			std::initializer_list<std::pair<uint16_t, Action>> actions) {
		std::array<ActionState, Action::kNumActions> map;
		map.fill(static_cast<ActionState>(-1));
		for (auto [i, action] : actions) {
			map[static_cast<size_t>(action)] = static_cast<ActionState>(i);
		}
		return map;
	}

public:
	constexpr explicit SubsetMapper(std::initializer_list<std::pair<uint16_t, Action>> actions) :
		toAction(buildToAction(actions)),
		toActionState(buildToActionState(actions)) {}

	const std::array<Action, kNumMapperActionStates> toAction;
	const std::array<ActionState, Action::kNumActions> toActionState;
};

